const ZERO_WIDTH_JOINER_SUFFIX = 'fe0f'

/** Turn an emoji into the key used by the downloaded images. */
export function emojiKey(emoji: string) {
  return [...emoji]
    .map((char) => char.codePointAt(0)?.toString(16) ?? '')
    .filter((code) => code && code !== ZERO_WIDTH_JOINER_SUFFIX)
    .join('-')
}

/** Image URL for an emoji, or undefined when no download exists. */
export function emojiImage(emoji: string) {
  return emojiImages[emojiKey(emoji)]
}

export default emojiImages
